rom_slot_t romset_identify(const uint8_t *data, size_t len) {
    if (len != ROM_IMAGE_SIZE) return ROM_UNKNOWN;
    uint8_t d[SHA1_DIGEST_LEN];
    sha1(data, len, d);
    for (int s = 0; s < ROM_SLOT_COUNT; s++) {
        if (romset_slots[s].has_sha1 &&
            memcmp(d, romset_slots[s].sha1, SHA1_DIGEST_LEN) == 0) {
            return (rom_slot_t)s;
        }
    }
    return ROM_UNKNOWN;
}
